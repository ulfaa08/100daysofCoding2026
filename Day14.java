public class OperatorTambahKurang {
    public static void main(String[] args) {
        // angkanya langsung ditulis di sini
        int angka1 = 50;
        int angka2 = 10;
        
        int tambah = angka1 + angka2;
        int kurang = angka1 - angka2;
        
        System.out.println("Angka pertama: " + angka1);
        System.out.println("Angka kedua: " + angka2);
        System.out.println("------------------------");
        System.out.println("Penjumlahan (+) : " + angka1 + " + " + angka2 + " = " + tambah);
        System.out.println("Pengurangan (-) : " + angka1 + " - " + angka2 + " = " + kurang);
    }
}
