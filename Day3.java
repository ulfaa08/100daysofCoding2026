public class EscapeSequence {
    public static void main(String[] args) {

        // \n = membuat baris baru
        System.out.println("Nama: Zulfa\NIM:D0224526");

        // \t = membuat tab/spasi
        System.out.println("Nama\t: Zulfa");
        System.out.println("NIM\t: D0224526 es");

        // \" = menampilkan tanda petik dua
        System.out.println("Dia berkata, \"Halo!\"");

        // \' = menampilkan tanda petik satu
        System.out.println("Ini adalah tanda petik satu: \'");

        // \\ = menampilkan karakter backslash
        System.out.println("Lokasi file: C:\\Users\\Zulfa");

        // \r = kembali ke awal baris
        System.out.println("Halo\rJava");

        // \b = backspace
        System.out.println("ABC\bD");
    }
}
