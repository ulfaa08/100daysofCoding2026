package com.mycompany.operatorincrementdecrement;

public class Main {
    public static void main(String[] args) {
        int a = 5;
        System.out.println("a awal = " + a);
        System.out.println("a++ = " + a++);
        System.out.println("++a = " + ++a);
        System.out.println("a-- = " + a--);
        System.out.println("--a = " + --a);
    }
}
