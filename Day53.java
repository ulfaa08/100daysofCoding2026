package perulangandowhilw;

public class PerulanganDoWhile {
    public static void main(String[] args) {
        
        System.out.println("=== Perulangan do-while ===");
        
        int i = 1;
        
        do {
            System.out.println("Perulangan ke-" + i);
            i++;
        } while (i <= 10);
        
        System.out.println("Selesai");
    }
}
